import pytest
from automaton import run

TEST_CASES = [
    ("-11-", "0: -11-"),
    ("-121-", "0: -121-"),
    ("-1221221-", "0: -1221221-"),
    ("-111211223321-", "0: -111211223321-"),
    ("-1231-", "0: -1231-"),
    ("-131-", "0: -131-"),
    ("-1-", "цепочек не найдено"),
    ("-2-1321-", "цепочек не найдено"),
    ("----", "цепочек не найдено"),
    ("-12-131-", "цепочек не найдено"),
    ("123123", "цепочек не найдено"),
    ("123--123-1231-", "цепочек не найдено"),
    ("-1a1-", "Ошибка: символ 'a' не принадлежит алфавиту {1, 2, 3, -}"),
    ("abc", "Ошибка: символ 'a' не принадлежит алфавиту {1, 2, 3, -}"),
    ("-123-", "цепочек не найдено"),
]

@pytest.mark.parametrize("input_str, expected", TEST_CASES)
def test_automaton(input_str, expected):
    assert run(input_str) == expected
